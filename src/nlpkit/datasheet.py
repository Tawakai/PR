"""Datasheet for Datasets (Gebru et al.), заполняется числами из результатов ПР 3."""
from nlpkit.config import results_dir


def _agr(a: dict | None) -> str:
    if not a:
        return "раунд ещё не завершён"
    return (f"n={a['n']}, совпадение {a['percent_agreement']:.1%}, Cohen's κ={a['cohen_kappa']} "
            f"({a['interpretation']}), Krippendorff's α={a['krippendorff_alpha']}")


def write(cfg: dict, s: dict) -> None:
    st, z, h = s["stats"], s["zipf"], s["heaps"]
    log = "\n".join(f"| {n} | {r} | {left} |" for n, r, left in s["filter_log"])
    ann = s.get("annotation", {})
    gold = ann.get("gold")
    terms = ", ".join(t[0] for t in s["terms"][:15])
    text = f"""# Datasheet: корпус аннотаций arXiv по физике неидеальной плазмы

*Формат: Datasheets for Datasets (Gebru et al., 2021). Файл создан автоматически; поля, помеченные TODO, заполните вручную.*

## 1. Мотивация
- **Для чего создан.** Для курсовых экспериментов по NLP в рамках диссертации (характеристики неидеальной плазмы): тематическая классификация и извлечение физических параметров из научных аннотаций.
- **Кто создал.** TODO: ФИО, кафедра, год.
- **Финансирование.** TODO.

## 2. Состав
- **Документов:** {st['n_docs']}; токенов {st['n_tokens']}; типов {st['n_types']}; TTR {st['ttr']} (на выборке 10 000 токенов {st['ttr_10k']}).
- **Что входит в документ:** заголовок и аннотация статьи (arXiv id, дата, основная и дополнительные категории, язык, длина).
- **Язык:** доля по langdetect среди собранных до фильтрации: {st['lang_share_collected']}; в итоговом корпусе: {st['lang_share_corpus']}.
- **Период публикации:** {st['date_min']} … {st['date_max']}.
- **Длина документа (токенов):** медиана {st['len_median']}, среднее {st['len_mean']}, 5–95 перцентиль {st['len_p05']}–{st['len_p95']}.
- **Подвыборки:** {st['n_keyword_docs']} документов найдены по ключевым фразам про неидеальную плазму, {st['n_base_docs']} взяты из категории physics.plasm-ph (по дате, от новых к старым).
- **Персональные данные.** Тексты аннотаций не содержат персональных данных пользователей. Имена авторов не сохраняются.

## 3. Процесс сбора
- **Источник:** официальный API arXiv (export.arxiv.org/api/query), только метаданные.
- **Как отбирались документы:** 1) поиск по ключевым фразам (strongly coupled plasma, non-ideal plasma, warm dense matter и др.) в профильных категориях, сортировка по релевантности; 2) остальные документы из категории physics.plasm-ph, сортировка по дате.
- **Соблюдение правил API:** пауза между запросами 3 с, идентифицирующий User-Agent.
- **Лицензия.** Метаданные arXiv (название, аннотация) распространяются как CC0. Полные тексты статей в корпус не входят. TODO: проверьте актуальные условия на info.arxiv.org.

## 4. Предобработка, очистка, дедупликация
Удаление формул `$...$`, нормализация Unicode, пробелов и кавычек (функция очистки из ПР 1). Дедупликация SimHash (64 бита, расстояние Хэмминга ≤ {s['simhash_k']}, шинглы по 3 слова).

| этап | удалено | осталось |
|---|---|---|
{log}

## 5. Статистические свойства
- **Закон Ципфа.** МНК в log-log: по рангам {z['core_ranks']} показатель α={z['alpha_core']} (R²={z['r2_core']}); по всем рангам α={z['alpha_full']} (R²={z['r2_full']}). Хвост искажает оценку: слова с частотой 1 (hapax: {st['hapax_share']:.1%} типов) образуют «ступеньку».
- **Закон Хипса.** V = K·N^β, K={h['K']}, β={h['beta']} (R²={h['r2']}).
- **Предметные термины (LLR против случайных статей en.wikipedia):** {terms}, … (всего {len(s['terms'])}, см. keywords_llr.csv).

## 6. Разметка
- **Задача:** бинарная классификация `nonideal` / `other` (инструкция: guidelines_v1.md, guidelines_v2.md).
- **Аннотаторы:** 2 (автор и коллега-докторант). TODO: опыт и квалификация.
- **Раунд 1:** {_agr(ann.get('round1'))}.
- **Раунд 2:** {_agr(ann.get('round2'))}.
- **Итоговая эталонная разметка:** {gold if gold else 'ещё не собрана'}.
- **Как делалась выборка для разметки:** половина примеров содержит ключевые слова неидеальной плазмы, половина случайная (стратификация, чтобы в выборке были оба класса). Доли классов в выборке поэтому не отражают долю классов в корпусе.

## 7. Рекомендуемые и нерекомендуемые применения
- Подходит для: обучения и сравнения классификаторов тем в области физики плазмы, оценки извлечения параметров.
- Не подходит для: оценки распространённости неидеальной плазмы в литературе (выборка не случайная); выводов о других языках и других предметных областях.

## 8. Известные ограничения и смещения
- Только аннотации, без полного текста; формулы вырезаны, поэтому численные параметры (Γ, T, n) часто потеряны.
- Подвыборка по ключевым фразам смещена к статьям, которые сами используют эти термины.
- Подвыборка из категории по дате смещена к последним годам.
- Корпус английский; казахский и русский тексты в нём не представлены.
- Эталонная разметка небольшая ({gold['n'] if gold else '—'} примеров) и не покрывает весь корпус.

## 9. Распространение и сопровождение
- **Распространение:** TODO (репозиторий курса, закрытый доступ).
- **Версия:** 1.0, дата сборки TODO. Повторная сборка: `python run.py download-arxiv`, затем `python run.py pr3`. Результаты запросов к API меняются со временем, поэтому точный состав корпуса зависит от даты скачивания; сам корпус зафиксирован в data/corpus.jsonl.
"""
    d = cfg["paths"]["reports"] / "pr3"
    d.mkdir(parents=True, exist_ok=True)
    (d / "datasheet.md").write_text(text, encoding="utf-8")
    print("Datasheet →", d / "datasheet.md")