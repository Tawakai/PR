doc = Document()
s = doc.styles["Normal"]
s.font.name = "Times New Roman"
s.font.size = Pt(12)
s.paragraph_format.line_spacing = 1.15
s.paragraph_format.space_after = Pt(6)
for sec in doc.sections:
    sec.top_margin = Cm(2); sec.bottom_margin = Cm(2)
    sec.left_margin = Cm(3); sec.right_margin = Cm(1.5)

def H(text, size=16):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text); r.bold = True; r.font.size = Pt(size)
    doc.add_paragraph()

def h(text):
    p = doc.add_paragraph(); r = p.add_run(text); r.bold = True; r.font.size = Pt(13)

def p(text):
    doc.add_paragraph(text)

def b(text):
    doc.add_paragraph(text, style="List Bullet")

def tbl(head, rows, cap=None):
    if cap:
        c = doc.add_paragraph(); c.add_run(cap).bold = True
    t = doc.add_table(rows=1, cols=len(head))
    t.style = "Light Grid Accent 1"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, x in enumerate(head):
        t.rows[0].cells[i].text = str(x)
        for r in t.rows[0].cells[i].paragraphs[0].runs:
            r.bold = True; r.font.size = Pt(10)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = str(v)
            for r in cells[i].paragraphs[0].runs:
                r.font.size = Pt(10)
    doc.add_paragraph()

